// DTCG JSON -> CSS custom properties. A small, dependency-free stand-in for Style Dictionary:
// same tiers and output shape (primitive vars on :root, semantic vars per [data-theme],
// spacing per [data-density], component vars that alias semantic ones).
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(new URL("../tokens/tokens.json", import.meta.url), "utf8"));
const isToken = (n) => n && typeof n === "object" && "$value" in n;
const flat = (node, path = []) =>
  Object.entries(node).flatMap(([k, v]) =>
    k.startsWith("$") ? [] : isToken(v) ? [[[...path, k], v.$value]] : flat(v, [...path, k]));

const varName = (path) => {
  const [tier, ...rest] = path;
  if (tier === "primitive") return `--${rest.join("-")}`;
  if (tier === "semantic") return `--color-${rest.join("-")}`;
  return `--${rest.join("-")}`;
};
// "{primitive.color.ink.0}" -> var(--color-ink-0); "{semantic.action}" -> var(--color-action)
const resolve = (v) => String(v).replace(/\{([^}]+)\}/g, (_, ref) => `var(${varName(ref.split("."))})`);
const block = (sel, entries, nameFn) =>
  `${sel} {\n${entries.map(([p, v]) => `  ${nameFn(p)}: ${resolve(v)};`).join("\n")}\n}\n`;

let css = "/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */\n";
css += block(":root", flat(src.primitive, ["primitive"]), varName);
for (const [theme, set] of Object.entries(src.semantic)) {
  const sel = theme === "light" ? `:root, [data-theme="light"]` : `[data-theme="${theme}"]`;
  css += block(sel, flat(set, ["semantic"]), varName);
}
for (const [density, set] of Object.entries(src.density)) {
  const sel = density === "comfortable" ? `:root, [data-density="comfortable"]` : `[data-density="${density}"]`;
  css += block(sel, flat(set, ["density"]), varName);
}
css += block(":root", flat(src.component, ["component"]), varName);
writeFileSync(new URL("../app/tokens.css", import.meta.url), css);
console.log("tokens: wrote app/tokens.css");
